"""
Takes the data from the csv file generated by generate_data.py and converts it into numpy objects.
"""

import numpy as np
import pandas as pd
from pathlib import Path
import json

def process_csv(csv_file: Path):

    # divide the dataset into training, validation and testing sets 
    # and store in separate npy files

    # set the ratios for training, validation and testing sets

    print("Reading Data")
    data = pd.read_csv(csv_file, sep=";")
    print("Data read: ", data.info())

    # load and convert from string to floats
    print("Processing stresses")
    stresses = np.stack([json.loads(sample) for sample in data['stresses']]).astype(np.float32).transpose(0, 2, 1)
    print("Stresses processed: ", stresses.shape)
    print("Processing strain energy densities")
    strain_energy_densities = np.stack([json.loads(sample) for sample in data['strain_energy_densities']]).astype(np.float32).transpose(0, 2, 1)
    print("Strain energy densities processed: ", strain_energy_densities.shape)
    volume_fractions = np.asarray(data['volfrac'], dtype=np.float32)
    print("Volume fractions processed: ", volume_fractions.shape)
    loads = np.stack([json.loads(sample) for sample in data['f']]).astype(np.float32)
    print("Loads processed: ", loads.shape)
    fixed_dofs = np.empty(len(data), dtype=object) # fixed_dofs have variable length
    for i, sample in enumerate(data["fixed_dofs"]):
        fixed_dofs[i] = np.asarray(json.loads(sample), dtype=np.int64)
    print("Fixed DOFs processed: ", fixed_dofs.shape)
    #! block for processing densities ai aided since I had a weird format and transposition issue
    print("Processing densities")
    densities = np.stack([
        np.asarray(json.loads(sample), dtype=np.float32)
        .reshape(64, 64)
        .T
        for sample in data["densities"]
    ])
    print("Densities processed: ", densities.shape)
    
    
    lengths = np.array([len(d) for d in fixed_dofs], dtype=np.int64)
    offsets = np.concatenate([[0], np.cumsum(lengths)])   # sample i = flat[offsets[i]:offsets[i+1]]
    fixed_dofs_flat = np.concatenate(fixed_dofs)

    out_file = csv_file.parent.parent / "processed" / "topopt_data.npz"
    out_file.parent.mkdir(exist_ok=True)
    np.savez(out_file,
            stresses=stresses,
            strain_energy_densities=strain_energy_densities,
            volume_fractions=volume_fractions,
            loads=loads,
            fixed_dofs_flat=fixed_dofs_flat,
            fixed_dofs_offsets=offsets,
            densities=densities)
    

if __name__ == "__main__":
    csv_file = Path(__file__).resolve().parent / "raw_data" / "topopt_data.csv"
    process_csv(csv_file)
